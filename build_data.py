#!/usr/bin/env python3
"""Bundle the Huckleberry CSV export (plus events.json and profile.json, if present) for the dashboard.

Writes
  data.js       plain bundle for local use (git-ignored)
  data.enc.js   passphrase-encrypted bundle for the published page (only when a
                passphrase is given via --passphrase-file, the PASSPHRASE env var,
                or a .passphrase file next to this script)

Usage:  python3 build_data.py [path/to/export.csv] [--events events.json]
                              [--passphrase-file .passphrase] [--no-plain]
With no CSV argument it picks the newest *.csv in this folder.
"""
import argparse, base64, csv, glob, json, os, sys

folder = os.path.dirname(os.path.abspath(__file__))
ap = argparse.ArgumentParser()
ap.add_argument("csv", nargs="?")
ap.add_argument("--events", default=os.path.join(folder, "events.json"))
ap.add_argument("--profile", default=os.path.join(folder, "profile.json"), help="name, birth date, formula density, targets, clinic weigh-ins (kept out of git)")
ap.add_argument("--passphrase-file", default=os.path.join(folder, ".passphrase"))
ap.add_argument("--no-plain", action="store_true", help="do not write the unencrypted data.js")
args = ap.parse_args()

src = args.csv
if not src:
    csvs = sorted(glob.glob(os.path.join(folder, "*.csv")), key=os.path.getmtime)
    if not csvs:
        sys.exit("No CSV found in " + folder)
    src = csvs[-1]

with open(src, newline="", encoding="utf-8-sig") as f:
    rows = list(csv.DictReader(f))
if not rows or "Type" not in rows[0] or "Start" not in rows[0]:
    sys.exit(f"{os.path.basename(src)} does not look like a Huckleberry export (needs Type and Start columns)")

events = None
if os.path.exists(args.events):
    with open(args.events, encoding="utf-8") as f:
        events = json.load(f)
    if not isinstance(events, list):
        sys.exit("events.json must contain a list of events")

profile = None
if os.path.exists(args.profile):
    with open(args.profile, encoding="utf-8") as f:
        profile = json.load(f)

bundle = {"rows": rows, "events": events, "profile": profile, "source": os.path.basename(src)}
payload = json.dumps(bundle, ensure_ascii=False, separators=(",", ":"))

if not args.no_plain:
    with open(os.path.join(folder, "data.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by build_data.py from " + os.path.basename(src) + " (plain, local use only)\n")
        f.write("window.HUCKLEBERRY_ROWS = " + json.dumps(rows, ensure_ascii=False, separators=(",", ":")) + ";\n")
        if events is not None:
            f.write("window.HUCKLEBERRY_EVENTS = " + json.dumps(events, ensure_ascii=False, separators=(",", ":")) + ";\n")
        if profile is not None:
            f.write("window.HUCKLEBERRY_PROFILE = " + json.dumps(profile, ensure_ascii=False) + ";\n")
    print(f"Wrote data.js: {len(rows)} rows from {os.path.basename(src)}" + (f", {len(events)} events" if events is not None else ", no events.json"))

passphrase = os.environ.get("PASSPHRASE")
if not passphrase and os.path.exists(args.passphrase_file):
    with open(args.passphrase_file, encoding="utf-8") as f:
        passphrase = f.read().strip()

if passphrase:
    try:
        from cryptography.hazmat.primitives.ciphers.aead import AESGCM
        from cryptography.hazmat.primitives.kdf.pbkdf2 import PBKDF2HMAC
        from cryptography.hazmat.primitives import hashes
    except ImportError:
        sys.exit("The 'cryptography' package is needed for encryption: pip install cryptography")
    salt, iv, iterations = os.urandom(16), os.urandom(12), 300_000
    key = PBKDF2HMAC(algorithm=hashes.SHA256(), length=32, salt=salt, iterations=iterations).derive(passphrase.encode("utf-8"))
    ct = AESGCM(key).encrypt(iv, payload.encode("utf-8"), None)
    b64 = lambda b: base64.b64encode(b).decode("ascii")
    enc = {"v": 1, "kdf": "PBKDF2-SHA256", "iter": iterations, "salt": b64(salt), "iv": b64(iv), "ct": b64(ct)}
    with open(os.path.join(folder, "data.enc.js"), "w", encoding="utf-8") as f:
        f.write("// Encrypted bundle generated by build_data.py (AES-256-GCM, PBKDF2-SHA256). Nothing readable without the passphrase.\n")
        f.write("window.HUCKLEBERRY_ENC = " + json.dumps(enc) + ";\n")
    print(f"Wrote data.enc.js: encrypted {len(payload):,} bytes")
else:
    print("No passphrase found (.passphrase file or PASSPHRASE env), so data.enc.js was not written.")
